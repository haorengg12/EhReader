/** 单画廊事务使用的 SQL；最终引用检查必须与下载/位置删除共用事务。 */
internal object DownloadDeletionSql {
    const val TAG_TABLES = "SELECT name FROM sqlite_master WHERE type = 'table' AND name IN ('DOWNLOAD_TAG', 'DOWNLOAD_TAG_STAT')"

    // F14 标签索引与下载删除共用事务；计数先扣减，关系行随后由外键级联删除。
    const val DECREMENT_TAGS = "UPDATE DOWNLOAD_TAG_STAT SET TAG_COUNT = TAG_COUNT - 1 WHERE EXISTS (SELECT 1 FROM DOWNLOAD_TAG t WHERE t.GID = ? AND t.NAMESPACE = DOWNLOAD_TAG_STAT.NAMESPACE AND t.TAG = DOWNLOAD_TAG_STAT.TAG)"
    const val REMOVE_EMPTY_TAGS = "DELETE FROM DOWNLOAD_TAG_STAT WHERE TAG_COUNT <= 0 AND EXISTS (SELECT 1 FROM DOWNLOAD_TAG t WHERE t.GID = ? AND t.NAMESPACE = DOWNLOAD_TAG_STAT.NAMESPACE AND t.TAG = DOWNLOAD_TAG_STAT.TAG)"
    const val REMOVE_DOWNLOAD = "DELETE FROM DOWNLOADS WHERE GID = ?"
    const val REMAINING_TAGS = "SELECT 1 FROM DOWNLOAD_TAG WHERE GID = ? LIMIT 1"
    const val REMOVE_LOCATION = "DELETE FROM DOWNLOAD_LOCATIONS WHERE GID = ?"
    const val REMOVE_UNREFERENCED_METADATA = "DELETE FROM GALLERY_METADATA WHERE GID = ? AND NOT EXISTS (SELECT 1 FROM DOWNLOADS WHERE GID = GALLERY_METADATA.GID) AND NOT EXISTS (SELECT 1 FROM DOWNLOAD_LOCATIONS WHERE GID = GALLERY_METADATA.GID) AND NOT EXISTS (SELECT 1 FROM HISTORY WHERE GID = GALLERY_METADATA.GID) AND NOT EXISTS (SELECT 1 FROM LOCAL_FAVORITES WHERE GID = GALLERY_METADATA.GID) AND NOT EXISTS (SELECT 1 FROM READING_STATE WHERE GID = GALLERY_METADATA.GID) AND NOT EXISTS (SELECT 1 FROM BOOKMARKS WHERE GID = GALLERY_METADATA.GID)"
}
